-- Tropic Line ShopCart schema. Running it drops and recreates everything.
DROP TABLE IF EXISTS reviews, order_items, orders, products, users CASCADE;

CREATE TABLE users (
  id            SERIAL PRIMARY KEY,
  name          TEXT NOT NULL,
  email         TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role          TEXT NOT NULL DEFAULT 'customer' CHECK (role IN ('customer', 'admin')),
  phone         TEXT,
  address       TEXT,
  city          TEXT,
  preferences   JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE products (
  id         SERIAL PRIMARY KEY,
  slug       TEXT NOT NULL UNIQUE,
  kind       TEXT NOT NULL CHECK (kind IN ('coffee', 'kit')),
  name       TEXT NOT NULL,
  country    TEXT,
  region     TEXT,
  latitude   NUMERIC(5, 2),
  altitude   TEXT,
  process    TEXT,
  variety    TEXT,
  harvest    TEXT,
  notes      TEXT[] NOT NULL DEFAULT '{}',
  story      TEXT,
  detail     TEXT,
  price      NUMERIC(10, 3) NOT NULL CHECK (price >= 0),
  stock      INTEGER NOT NULL DEFAULT 0,
  bag        TEXT,
  image      TEXT,
  image_alt  TEXT,
  position   INTEGER NOT NULL DEFAULT 0
);

-- Order numbers are sequential and start at 1001, shown as TL-1001.
CREATE TABLE orders (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
  user_id    INTEGER REFERENCES users(id) ON DELETE SET NULL,
  email      TEXT NOT NULL,
  name       TEXT NOT NULL,
  phone      TEXT NOT NULL,
  address    TEXT NOT NULL,
  city       TEXT NOT NULL,
  subtotal   NUMERIC(10, 3) NOT NULL,
  shipping   NUMERIC(10, 3) NOT NULL,
  total      NUMERIC(10, 3) NOT NULL,
  status     TEXT NOT NULL DEFAULT 'Roasting Tuesday'
             CHECK (status IN ('Roasting Tuesday', 'Posted', 'Delivered', 'Cancelled')),
  payment    TEXT NOT NULL DEFAULT 'cash on delivery',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE order_items (
  id         SERIAL PRIMARY KEY,
  order_id   INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES products(id),
  grind      TEXT,
  qty        INTEGER NOT NULL,
  unit_price NUMERIC(10, 3) NOT NULL
);

CREATE TABLE reviews (
  id         SERIAL PRIMARY KEY,
  product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  rating     INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
  body       TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX orders_user_idx ON orders(user_id);
CREATE INDEX order_items_order_idx ON order_items(order_id);
CREATE INDEX reviews_product_idx ON reviews(product_id);
